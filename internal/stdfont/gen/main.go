// Command gen builds the stand-ins for the standard fonts Symbol and
// ZapfDingbats: subsets of DejaVu Sans holding the glyphs of their
// character sets, and tables of their built-in encodings, AFM widths and
// what each glyph stands for in Unicode.
//
//	go run ./internal/stdfont/gen -src dir
//
// dir holds Symbol.afm and ZapfDingbats.afm (Adobe's Core 14 metrics),
// glyphlist.txt and zapfdingbats.txt (Adobe's glyph lists, from
// https://github.com/adobe-type-tools/agl-aglfn).
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/go-opentype/fonts/dejavusans"
	"github.com/go-opentype/opentype"
)

// private maps glyph names Adobe's list puts in the private use area to
// the standard characters that look the same.
var private = map[string]rune{
	"arrowvertex": 0x23D0, "arrowhorizex": 0x23AF, "radicalex": 0x203E,
	"registersans": 0xAE, "copyrightsans": 0xA9, "trademarksans": 0x2122,
	"registerserif": 0xAE, "copyrightserif": 0xA9, "trademarkserif": 0x2122,
	"parenlefttp": 0x239B, "parenleftex": 0x239C, "parenleftbt": 0x239D,
	"bracketlefttp": 0x23A1, "bracketleftex": 0x23A2, "bracketleftbt": 0x23A3,
	"bracelefttp": 0x23A7, "braceleftmid": 0x23A8, "braceleftbt": 0x23A9,
	"braceex": 0x23AA, "integralex": 0x23AE,
	"parenrighttp": 0x239E, "parenrightex": 0x239F, "parenrightbt": 0x23A0,
	"bracketrighttp": 0x23A4, "bracketrightex": 0x23A5, "bracketrightbt": 0x23A6,
	"bracerighttp": 0x23AB, "bracerightmid": 0x23AC, "bracerightbt": 0x23AD,
	// Symbol's Greek letters, which the glyph list gives as signs.
	"Delta": 0x0394, "Omega": 0x03A9, "mu": 0x03BC,
}

// alternatives are characters drawn for a glyph when DejaVu Sans lacks the
// one it stands for.
var alternatives = map[rune][]rune{
	0x2329: {0x27E8, 0x3008}, 0x232A: {0x27E9, 0x3009},
	0x23AF: {0x2500}, 0x23D0: {0x2502},
}

type glyph struct {
	name  string
	r     rune
	width int
	gid   opentype.GlyphIndex // in DejaVu Sans, then in the subset
}

type font struct {
	ident  string // Go identifier
	file   string
	enc    [256]string
	glyphs map[string]*glyph
}

func main() {
	src := flag.String("src", "", "directory with the AFMs and glyph lists")
	out := flag.String("o", "internal/stdfont", "output directory")
	flag.Parse()
	agl := readList(filepath.Join(*src, "glyphlist.txt"))
	zapf := readList(filepath.Join(*src, "zapfdingbats.txt"))
	dv, err := opentype.Parse(dejavusans.TTF)
	if err != nil {
		log.Fatal(err)
	}
	var code bytes.Buffer
	code.WriteString("// Code generated by internal/stdfont/gen; DO NOT EDIT.\n\npackage stdfont\n\nimport _ \"embed\"\n\n")
	for _, f := range []*font{
		{ident: "Symbol", file: "Symbol"},
		{ident: "ZapfDingbats", file: "ZapfDingbats"},
	} {
		readAFM(f, filepath.Join(*src, f.file+".afm"))
		var gids []opentype.GlyphIndex
		var missing []string
		for _, g := range f.glyphs {
			r, ok := private[g.name]
			if !ok {
				if f.ident == "ZapfDingbats" && g.name != "space" {
					r, ok = zapf[g.name]
				} else {
					r, ok = agl[g.name]
				}
			}
			if !ok || r >= 0xE000 && r <= 0xF8FF {
				missing = append(missing, g.name)
				continue
			}
			g.r = r
			gid, ok := dv.GlyphIndex(r)
			for _, alt := range alternatives[r] {
				if ok && gid != 0 {
					break
				}
				gid, ok = dv.GlyphIndex(alt)
			}
			if !ok || gid == 0 {
				missing = append(missing, fmt.Sprintf("%s (U+%04X)", g.name, r))
				continue
			}
			g.gid = gid
			gids = append(gids, gid)
		}
		sort.Strings(missing)
		if len(missing) > 0 {
			log.Printf("%s: no glyph for %s", f.ident, strings.Join(missing, ", "))
		}
		data, remap, err := dv.SubsetTrueType(gids)
		if err != nil {
			log.Fatal(err)
		}
		for _, g := range f.glyphs {
			if g.gid != 0 {
				g.gid = remap[g.gid]
			}
		}
		ttf := strings.ToLower(f.ident) + ".ttf"
		if err := os.WriteFile(filepath.Join(*out, ttf), data, 0o644); err != nil {
			log.Fatal(err)
		}
		log.Printf("%s: %d glyphs, %d bytes", ttf, len(gids), len(data))
		writeTables(&code, f, ttf)
	}
	src2, err := format.Source(code.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "tables.go"), src2, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeTables(w *bytes.Buffer, f *font, ttf string) {
	names := make([]string, 0, len(f.glyphs))
	for n := range f.glyphs {
		names = append(names, n)
	}
	sort.Strings(names)
	idx := map[string]int{}
	fmt.Fprintf(w, "//go:embed %s\nvar %sTTF []byte\n\n", ttf, strings.ToLower(f.ident[:1])+f.ident[1:])
	fmt.Fprintf(w, "var %s = &Font{\n\tName: %q,\n\tttf: &%sTTF,\n\tglyphs: []Glyph{\n", f.ident, f.ident, strings.ToLower(f.ident[:1])+f.ident[1:])
	for i, n := range names {
		g := f.glyphs[n]
		idx[n] = i
		fmt.Fprintf(w, "\t\t{%q, %d, %d, %d},\n", n, g.r, g.width, g.gid)
	}
	w.WriteString("\t},\n\tcodes: [256]uint8{")
	for c, n := range f.enc {
		if n != "" {
			fmt.Fprintf(w, "%d: %d, ", c, idx[n]+1)
		}
	}
	w.WriteString("},\n}\n\n")
}

// readAFM reads the glyphs, widths and built-in encoding of an AFM file.
func readAFM(f *font, path string) {
	file, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer file.Close()
	f.glyphs = map[string]*glyph{}
	sc := bufio.NewScanner(file)
	for sc.Scan() {
		line := sc.Text()
		if !strings.HasPrefix(line, "C ") {
			continue
		}
		code, width, name := -1, 0, ""
		for _, part := range strings.Split(line, ";") {
			fields := strings.Fields(part)
			if len(fields) < 2 {
				continue
			}
			switch fields[0] {
			case "C":
				code, _ = strconv.Atoi(fields[1])
			case "WX":
				width, _ = strconv.Atoi(fields[1])
			case "N":
				name = fields[1]
			}
		}
		if name == "" {
			continue
		}
		f.glyphs[name] = &glyph{name: name, width: width}
		if code >= 0 && code < 256 {
			f.enc[code] = name
		}
	}
}

// readList reads a glyph list: name;XXXX lines, the first entry of a name
// winning.
func readList(path string) map[string]rune {
	data, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	m := map[string]rune{}
	for _, line := range strings.Split(string(data), "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		name, val, ok := strings.Cut(strings.TrimSpace(line), ";")
		if !ok {
			continue
		}
		v, err := strconv.ParseUint(strings.Fields(val)[0], 16, 32)
		if err != nil {
			continue
		}
		if _, dup := m[name]; !dup {
			m[name] = rune(v)
		}
	}
	return m
}
